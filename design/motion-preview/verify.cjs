const { chromium } = require(process.env.CX_NODE_MODULES + '/playwright');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');

(async () => {
  const output = path.resolve(__dirname, '../../.artifacts/motion-preview');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: process.env.CX_PREVIEW_BROWSER || 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1280, height: 1040 }, reducedMotion: 'no-preference' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.route('https://**/*', route => { errors.push('Unexpected external request: ' + route.request().url()); return route.abort(); });
  await page.goto('file:///' + path.join(__dirname, 'index.html').replaceAll('\\', '/'));
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(() => gsap.version), '3.15.0');
  assert.equal(await page.locator('.card').count(), 6);
  assert.equal(await page.evaluate(() => cxLiquid.mode), 'webgl');
  const shaderBefore = await page.evaluate(() => ({ frames:cxLiquid.frames, time:cxLiquid.elapsed, pixel:cxLiquid.pixels }));
  await page.waitForTimeout(250);
  const shaderAfter = await page.evaluate(() => ({ frames:cxLiquid.frames, time:cxLiquid.elapsed, pixel:cxLiquid.pixels }));
  assert.ok(shaderAfter.frames > shaderBefore.frames && shaderAfter.time > shaderBefore.time);
  assert.ok(shaderAfter.pixel[3] === 255 && shaderAfter.pixel.slice(0,3).some(value => value > 20));
  assert.ok(await page.locator('.card').first().evaluate(element => element.querySelector('.card-actions').getBoundingClientRect().bottom <= element.getBoundingClientRect().bottom), 'card actions remain inside the glass frame');
  await page.screenshot({ path: path.join(output, 'library.png'), fullPage: true });
  const palette = await page.evaluate(() => {
    const canvas = document.querySelector('#liquid-canvas'), gl = canvas.getContext('webgl'), data = new Uint8Array(4), samples=[];
    for (let y=1;y<10;y++) for(let x=1;x<10;x++) {
      gl.readPixels(Math.floor(canvas.width*x/10),Math.floor(canvas.height*y/10),1,1,gl.RGBA,gl.UNSIGNED_BYTE,data);
      samples.push((Math.max(...data.slice(0,3))-Math.min(...data.slice(0,3)))/Math.max(1,...data.slice(0,3)));
    }
    return { mean:samples.reduce((a,b)=>a+b,0)/samples.length, max:Math.max(...samples) };
  });
  assert.ok(palette.mean < .22 && palette.max < .32, 'background uses restrained graphite and silver');
  for (let i=0;i<10;i++) { await page.mouse.move(440+i*48,650+Math.sin(i*.8)*65); await page.waitForTimeout(100); }
  assert.ok(await page.evaluate(() => cxLiquid.disturbances > 0), 'pointer movement deposits persistent fluid momentum');
  await page.screenshot({ path: path.join(output, 'liquid-stirred.png'), fullPage: true });
  await page.waitForTimeout(2700);
  assert.equal(await page.evaluate(() => cxLiquid.disturbances), 0, 'pointer disturbances dissipate');
  const poster = page.locator('.card .poster').first();
  await poster.hover(); await page.waitForTimeout(200);
  assert.ok(await poster.evaluate(element => gsap.getProperty(element, 'scaleX')) > 1.02);
  assert.ok(await page.locator('.card').first().evaluate(element => gsap.getProperty(element, 'y')) < -3);
  assert.equal(await page.locator('.card-sheen').first().evaluate(element => getComputedStyle(element).opacity), '1');
  await page.screenshot({ path: path.join(output, 'card-shimmer.png'), fullPage: true });
  await page.waitForTimeout(600);
  assert.equal(await page.locator('.card-sheen').first().evaluate(element => getComputedStyle(element).opacity), '0');
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  assert.equal(await page.evaluate(() => cxLiquid.running), false);
  const shaderPaused = await page.evaluate(() => cxLiquid.elapsed);
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(() => cxLiquid.elapsed), shaderPaused);
  assert.equal(await page.evaluate(() => gsap.globalTimeline.getChildren(true, true, true).filter(animation => animation.isActive()).length), 0);
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.waitForTimeout(50);
  assert.equal(await page.evaluate(() => gsap.globalTimeline.getChildren(true, true, true).filter(animation => animation.isActive() && animation.data === 'ambient').length), 1);
  await page.locator('.card .cover-button').first().click();
  await page.waitForTimeout(250);
  assert.equal(await page.locator('#detail-name').textContent(), '雾海回声');
  await page.screenshot({ path: path.join(output, 'details.png'), fullPage: true });
  await page.locator('.card .cover-button').nth(1).click({ delay: 5 });
  await page.locator('.card .cover-button').nth(2).click({ delay: 5 });
  await page.keyboard.press('Escape'); await page.waitForTimeout(250);
  assert.equal(await page.locator('#drawer').isVisible(), false);
  await page.locator('.card .favorite').nth(1).click();
  assert.equal(await page.locator('#favorites-count').textContent(), '3');
  await page.locator('[data-nav="favorite"]').click();
  assert.equal(await page.locator('.card').count(), 3);
  await page.locator('#view').click(); await page.waitForTimeout(250);
  assert.equal(await page.locator('#results').getAttribute('class'), 'results list-mode');
  await page.locator('#search').fill('没有这个游戏');
  assert.equal(await page.locator('.card').count(), 0);
  assert.equal(await page.locator('.empty').count(), 1);
  await page.keyboard.press('Control+f');
  assert.equal(await page.locator('#search').evaluate(element => element === document.activeElement), true);
  await page.locator('#search').fill(''); await page.locator('[data-nav="all"]').click();
  await page.locator('#speed').selectOption('2.5'); await page.locator('#replay').click();
  await page.locator('#reduce').check(); await page.waitForTimeout(30);
  assert.equal(await page.evaluate(() => cxLiquid.running), false);
  assert.equal(await page.evaluate(() => gsap.globalTimeline.getChildren(true, true, true).filter(animation => animation.isActive()).length), 0);
  assert.equal(await page.locator('.page-header').evaluate(element => getComputedStyle(element).opacity), '1');
  await page.locator('.card .cover-button').first().click();
  assert.equal(await page.locator('#drawer').evaluate(element => getComputedStyle(element).opacity), '1');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.evaluate(() => cxLiquid.running), false);
  await page.locator('#reduce').uncheck(); await page.locator('#replay').click();
  assert.equal(await page.evaluate(() => gsap.globalTimeline.getChildren(true, true, true).filter(animation => animation.isActive()).length), 0);
  await page.keyboard.press('Escape');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.locator('#speed').selectOption('1');
  await page.locator('#demo').click(); await page.waitForTimeout(4500);
  assert.equal(await page.locator('#drawer').isVisible(), false);
  assert.equal(await page.locator('#demo').textContent(), '▷ 自动演示');
  assert.equal(await page.evaluate(() => gsap.globalTimeline.getChildren(true, true, true).filter(animation => animation.isActive() && animation.data !== 'ambient').length), 0);
  assert.ok(await page.evaluate(() => gsap.globalTimeline.getChildren(true, true, true).filter(animation => animation.isActive() && animation.data === 'ambient').length) <= 1);
  await page.setViewportSize({ width: 760, height: 1000 }); await page.waitForTimeout(250);
  await page.screenshot({ path: path.join(output, 'compact.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(await page.locator('.card').first().evaluate(element => element.querySelector('.card-actions').getBoundingClientRect().bottom <= element.getBoundingClientRect().bottom), 'compact card actions remain inside frame');
  await page.locator('.card .cover-button').first().click();
  await page.waitForTimeout(250);
  assert.ok(await page.locator('#drawer').evaluate(element => element.getBoundingClientRect().right <= innerWidth));
  assert.deepEqual(errors, []);
  await page.evaluate(() => { const canvas=document.querySelector('#liquid-canvas'); canvas.getContext('webgl').getExtension('WEBGL_lose_context').loseContext(); });
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(() => cxLiquid.mode), 'static-fallback');
  assert.equal(await page.evaluate(() => cxLiquid.running), false);
  assert.equal(await page.locator('.liquid-fallback').isVisible(), true);
  const report = { gsap: '3.15.0', version: '0.6.0', result: 'passed', palette, coverage: ['offline assets', 'cover hover', 'card lift', 'one-shot sheen cleanup', 'background pause', 'single foreground light band', 'detail switching', 'Escape', 'favorite state', 'navigation', 'list view', 'search', 'keyboard focus', 'mid-animation reduced motion', 'OS reduced motion', 'one-shot demo cleanup', 'compact layout', 'WebGL shader compilation', 'live shader frames', 'background shader freeze', 'shader reduced motion', 'context loss fallback', 'low saturation graphite/silver spectrum', 'pointer stirring', 'ripple dissipation'], errors };
  fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify(report, null, 2));
  console.log('PASS: GSAP preview interactions, reduced motion, cleanup and responsive layout. ' + output);
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
